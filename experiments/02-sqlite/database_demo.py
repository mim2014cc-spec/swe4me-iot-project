from flask import Flask

# สร้างแอป Flask ขึ้นมา
app = Flask(__name__)


@app.route("/")
def home():
  # ฟังก์ชันนี้จะตอบกลับข้อความเมื่อเปิดหน้าเว็บที่หน้าแรก
  return "สวัสดีจาก Flask!"


if __name__ == "__main__":
  # รันเซิร์ฟเวอร์บนพอร์ต 5000 และอนุญาตให้เข้าถึงจากเครื่องอื่นได้
  # debug=False จะช่วยป้องกันการรีโหลดอัตโนมัติซ้ำ ๆ เมื่อทำงานกับนักเรียนเริ่มต้น
  app.run(host="0.0.0.0", port=5000, debug=False)